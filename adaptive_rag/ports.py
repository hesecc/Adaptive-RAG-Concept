"""Role contracts. Adapters are injected; importing a role performs no I/O."""

from typing import Any, Protocol, Sequence

from .domain import (
    AccessContext, ChildChunk, Coverage, Draft, Evidence, Hit, IngestRequest,
    IngestResult, ParentChunk, Plan, PreparedDocument, QueryRequest,
    Section, Snapshot, SubQuery, Verification,
)


class Parser(Protocol):
    def parse(self, request: IngestRequest) -> tuple[Section, ...]: ...


class Cleaner(Protocol):
    def clean(self, sections: Sequence[Section]) -> tuple[Section, ...]: ...


class Chunker(Protocol):
    def chunk(self, request: IngestRequest, revision_id: str, sections: Sequence[Section]) -> tuple[tuple[ParentChunk, ...], tuple[ChildChunk, ...]]: ...


class ObjectStore(Protocol):
    def put(self, content: bytes) -> str: ...
    def get(self, key: str) -> bytes: ...


class KnowledgeStore(Protocol):
    def stage(self, document: PreparedDocument) -> IngestResult: ...
    def get_job(self, tenant_id: str, job_id: str) -> dict[str, Any]: ...
    def list_documents(self, tenant_id: str) -> list[dict[str, Any]]: ...
    def publish(self, tenant_id: str, job_id: str, expected_generation: str | None) -> Snapshot: ...
    def open_snapshot(self, tenant_id: str, generation: str | None = None) -> Snapshot | None: ...
    def list_chunks(self, snapshot: Snapshot, access: AccessContext, sku: str | None = None) -> tuple[ChildChunk, ...]: ...
    def get_parents(self, snapshot: Snapshot, parent_ids: Sequence[str], access: AccessContext) -> tuple[ParentChunk, ...]: ...
    def delete_document(self, tenant_id: str, document_id: str, expected_generation: str | None) -> Snapshot: ...
    def rollback(self, tenant_id: str, generation: str, expected_generation: str | None) -> Snapshot: ...
    def set_access(self, tenant_id: str, document_id: str, allowed_subjects: tuple[str, ...] | None = None,
                   revoked: bool | None = None,
                   data_domains: tuple[str, ...] | None = None) -> None: ...


class Planner(Protocol):
    async def plan(self, request: QueryRequest) -> Plan: ...


class QueryTransform(Protocol):
    async def transform(self, queries: Sequence[SubQuery], request: QueryRequest) -> tuple[SubQuery, ...]: ...


class Retriever(Protocol):
    async def search(self, query: SubQuery, chunks: Sequence[ChildChunk], limit: int) -> tuple[Hit, ...]: ...


class Fusion(Protocol):
    def fuse(self, query: SubQuery, lanes: Sequence[Sequence[Hit]], limit: int) -> tuple[Hit, ...]: ...


class Reranker(Protocol):
    async def rank(self, query: SubQuery, hits: Sequence[Hit], limit: int) -> tuple[Hit, ...]: ...


class EvidenceJudge(Protocol):
    async def assess(self, queries: Sequence[SubQuery], evidence: Sequence[Evidence]) -> Coverage: ...


class Generator(Protocol):
    async def generate(self, plan: Plan, evidence: Sequence[Evidence]) -> Draft: ...


class Verifier(Protocol):
    async def verify(self, draft: Draft, evidence: Sequence[Evidence]) -> Verification: ...


class AnswerVerifier(Verifier, Protocol):
    """Optional semantic review; original questions are required to check omissions."""
    async def evaluate(self, plan: Plan, draft: Draft, evidence: Sequence[Evidence]) -> Verification: ...


class Embedder(Protocol):
    """Future cloud adapter. Document/query encoders must share model revision."""
    async def embed(self, texts: Sequence[str]) -> tuple[tuple[float, ...], ...]: ...


class DecisionPolicy(Protocol):
    """Future rule/Laya policy; output never grants access or raises budgets."""
    async def decide(self, state: dict[str, Any]) -> dict[str, Any]: ...


class TraceSink(Protocol):
    def save(self, trace: dict[str, Any]) -> None: ...
    def get(self, tenant_id: str, trace_id: str) -> dict[str, Any]: ...
